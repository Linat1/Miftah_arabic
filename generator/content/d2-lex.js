  'أَنِيقٌ': 'أَنِيقُونَ', 'عَصْرِيٌّ': 'عَصْرِيُّونَ', 'تَقْلِيدِيٌّ': 'تَقْلِيدِيُّونَ', 'رَسْمِيٌّ': 'رَسْمِيُّونَ', 'مُحْتَشِمٌ': 'مُحْتَشِمُونَ',
