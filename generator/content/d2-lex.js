// clothes: gender, plural, “this …”
const ITEM = {
  'قَمِيصٌ': ['m.', 'قُمْصَانٌ', 'هٰذَا القَمِيصُ'], 'قَمِيصَةٌ': ['f.', 'قَمِيصَاتٌ', 'هٰذِهِ القَمِيصَةُ'], 'سِرْوَالٌ': ['m.', 'سَرَاوِيلُ', 'هٰذَا السِّرْوَالُ'],
  'تَنُّورَةٌ': ['f.', 'تَنَانِيرُ', 'هٰذِهِ التَّنُّورَةُ'], 'فُسْتَانٌ': ['m.', 'فَسَاتِينُ', 'هٰذَا الفُسْتَانُ'], 'مِعْطَفٌ': ['m.', 'مَعَاطِفُ', 'هٰذَا المِعْطَفُ'],
  'سُتْرَةٌ': ['f.', 'سُتَرٌ', 'هٰذِهِ السُّتْرَةُ'], 'حِذَاءٌ': ['m.', 'أَحْذِيَةٌ', 'هٰذَا الحِذَاءُ'], 'حِجَابٌ': ['m.', 'أَحْجِبَةٌ', 'هٰذَا الحِجَابُ'],
  'قُبَّعَةٌ': ['f.', 'قُبَّعَاتٌ', 'هٰذِهِ القُبَّعَةُ'], 'حِزَامٌ': ['m.', 'أَحْزِمَةٌ', 'هٰذَا الحِزَامُ'], 'حَقِيبَةٌ': ['f.', 'حَقَائِبُ', 'هٰذِهِ الحَقِيبَةُ'],
  'نَظَّارَةٌ': ['f.', 'نَظَّارَاتٌ', 'هٰذِهِ النَّظَّارَةُ'],
};

function adjForms(ar) {
  const [m, f] = ar.split(' / ');
  if (!f) return undefined;
  const base = m.replace(/^غَيْرُ /, '');
  const pl = ADJ_PL[base] ? (m.startsWith('غَيْرُ') ? `غَيْرُ ${ADJ_PL[base]}` : ADJ_PL[base]) : undefined;
  return { tag: 'm · f · pl', forms: [...(pl ? [{ l: 'pl.', ar: pl }] : []), { l: 'f.', ar: f }, { l: 'm.', ar: m }] };
}
function itemForms(ar) {
  const it = ITEM[ar];
  if (!it) return undefined;
  return { tag: `${it[0]} · pl`, forms: [{ l: 'pl.', ar: it[1] }, { l: 'this', ar: it[2] }, { l: it[0], ar: it[0] === 'm.' ? 'مُذَكَّرٌ' : 'مُؤَنَّثٌ' }] };
}
function formsFor(code, extra = {}) {
  const out = {};
  D.site(code).vocab.forEach((g) => g.items.forEach((it) => {
    const f = itemForms(it.ar) || adjForms(it.ar);
    if (f) out[it.ar] = f;
  }));
  return { ...out, ...extra };
}

module.exports = { formsFor, adjForms, itemForms, ADJ_PL, ITEM };
